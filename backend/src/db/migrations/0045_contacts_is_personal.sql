-- =============================================================================
-- 0045: Флаг is_personal для контактов.
-- Позволяет отделять личные контакты (семья, друзья, знакомые) от рабочих лидов.
-- Для личных контактов:
--   1. CRM не создаёт сделки при входящих сообщениях (suppress_deal_creation = true).
--   2. Сообщения полностью игнорируются CRM (не пишутся в deal_messages,
--      не скармливаются AI-агенту, не вызывают автоответов).
--   3. Сообщения НЕ помечаются прочитанными на стороне транспорта, чтобы
--      пользователь видел уведомления на телефоне и мог общаться как обычно.
-- =============================================================================

ALTER TABLE contacts ADD COLUMN IF NOT EXISTS is_personal BOOLEAN NOT NULL DEFAULT false;

CREATE INDEX IF NOT EXISTS idx_contacts_is_personal ON contacts(tenant_id, is_personal) WHERE deleted_at IS NULL;
