-- =============================================================================
-- 0001: Глобальная платформенная роль (superadmin-панель)
--
-- Тенантные роли (owner/admin/...) управляют доступом внутри тенанта и не
-- могут служить гейтом платформенной админки: владелец любого тенанта
-- получил бы доступ ко всем данным платформы. Отдельная глобальная роль
-- живёт в users.platform_role и не зависит от tenant_id.
--
-- Идемпотентен: безопасно выполнять повторно (ADD COLUMN IF NOT EXISTS,
-- ON CONFLICT-подобный UPDATE по условию).
-- =============================================================================

ALTER TABLE users ADD COLUMN IF NOT EXISTS platform_role TEXT;

-- Владелец платформы — сид-пользователь деплоя GETVOXLY.
UPDATE users
SET platform_role = 'platform_owner', updated_at = now()
WHERE phone = '+79150946944' AND platform_role IS NULL;
