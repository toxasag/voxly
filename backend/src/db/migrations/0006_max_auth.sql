-- =============================================================================
-- 0006: Привязка MAX (RuMAX) к пользователю и к сессии подтверждения
--
-- Аналогично Telegram: коды подтверждения доставляются через бота платформы MAX,
-- поэтому нужен users.max_user_id, а сессии подтверждения должны помнить, в
-- какой MAX-диалог уже привязан код.
--
-- Идемпотентна: безопасна к повторному запуску.
-- =============================================================================

-- -----------------------------------------------------------------------------
-- 1. Привязка MAX к пользователю
-- -----------------------------------------------------------------------------
-- VARCHAR(128), а не BIGINT как telegram_chat_id: MAX отдаёт user_id числом, но
-- документация не фиксирует его разрядность, и хранение строкой избавляет от
-- потери точности при выходе за пределы int64.
ALTER TABLE users ADD COLUMN IF NOT EXISTS max_user_id VARCHAR(128);
ALTER TABLE users ADD COLUMN IF NOT EXISTS max_username TEXT;

-- Один MAX-аккаунт не должен управлять несколькими учётными записями:
-- иначе в один диалог приходили бы коды для разных логинов.
CREATE UNIQUE INDEX IF NOT EXISTS idx_users_max_user_id
  ON users (max_user_id)
  WHERE max_user_id IS NOT NULL;

-- -----------------------------------------------------------------------------
-- 2. Привязка MAX к сессии подтверждения
-- -----------------------------------------------------------------------------
-- Без этой колонки канал `max` не мог бы работать так же, как telegram: код
-- генерируется только когда известно, куда его отправлять, и после привязки по
-- deep-link сессия должна помнить адресата, чтобы register/login связали его с
-- создаваемым пользователем.
ALTER TABLE auth_sessions ADD COLUMN IF NOT EXISTS max_user_id VARCHAR(128);

-- app_user — непривилегированная роль пула (миграция 0002), она не владелец
-- таблицы, поэтому права на колонки нужны явно.
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'app_user') THEN
    EXECUTE 'GRANT UPDATE (max_user_id, max_username) ON users TO app_user';
    EXECUTE 'GRANT SELECT, INSERT, UPDATE, DELETE ON auth_sessions TO app_user';
  END IF;
END;
$$;
