"use client";

import { useCallback, useSyncExternalStore } from "react";

// ---------------------------------------------------------------------------
// Определение мобильного режима и способа ввода.
//
// Граница и запрос
// ----------------
// `MOBILE_VIEWPORT` — константа, а не CSS-переменная: переменные не работают
// внутри медиазапросов, это ограничение CSS, а не сборки.
//
// Запрос — `max-width: 767px`, на пиксель меньше границы. Брейкпоинты в проекте
// дефолтные (`globals.css` содержит только `@import "tailwindcss"` без блока
// `@theme`, а `tailwind.config.ts` в Tailwind 4 без директивы `@config` вообще не
// загружается), значит `md:` — это `min-width: 768px`. При запросе
// `max-width: 768px` на ровно 768px истинны оба условия: `md:`-классы
// применяются, и хук говорит «мобильный» — на планшете в портрете вышла бы смесь
// режимов. 767px делает хук точным дополнением к `md:`.
//
// У Twenty здесь `max-width: 768px` (`useIsMobile.ts`) — осознанное отклонение от
// референса: у них раскладка на styled-components со своими медиазапросами, а не
// на утилитах Tailwind, поэтому пересечение на одном пикселе им ничего не ломает.
//
// Где эти хуки уместны, а где нет
// -------------------------------
// **Структурную раскладку на них строить нельзя.** `matchMedia` при серверном
// рендере недоступен, поэтому на первом рендере хук обязан вернуть `false`; если
// от него зависят сайдбар, отступы или ширина панели, телефон сначала покажет
// десктопную раскладку и дёрнется после гидратации. Такие вещи делаются
// префиксами Tailwind (`hidden md:flex`, `md:pl-60`, `md:max-w-[500px]`) — они
// работают в SSR без JS и без вспышки.
//
// Этот проект уже дважды решал ту же задачу именно так: состояние сайдбара
// читается из cookie на сервере (`(dashboard)/layout.tsx`), тема ставится
// блокирующим скриптом до первой отрисовки (`app/layout.tsx`).
//
// Хуки нужны там, где CSS не выражает поведение: не рендерить колонку чекбоксов,
// не навешивать обработчики ресайза и drag, выбрать компонент палитры поиска.
// Вспышка там не видна — меняется не геометрия, а доступность действий.
//
// Почему без `react-responsive`
// -----------------------------
// У Twenty эти хуки на `react-responsive`. Здесь зависимости нет, и добавлять её
// не нужно: `useSyncExternalStore` из React 19 решает ту же задачу и делает это
// корректнее при SSR — у него отдельный серверный снимок (третий аргумент),
// поэтому значение на сервере задаётся явно, а не выводится из отсутствия
// `window`.
// ---------------------------------------------------------------------------

/** Граница мобильного режима — она же граница Tailwind `md:`. */
export const MOBILE_VIEWPORT = 768;

/** Точное дополнение к `md:`: на 768px уже десктоп. */
const MOBILE_QUERY = `(max-width: ${MOBILE_VIEWPORT - 1}px)`;

/**
 * Способ ввода, а не размер экрана.
 *
 * Ширина окна говорит о месте под раскладку, а не о том, как пользователь
 * указывает: узкое окно на десктопе всё ещё поддерживает hover, планшет в
 * ландшафте — нет. Ветвить взаимодействие по ширине — дефект, про который прямо
 * написано в комментарии `useIsTouchDevice.ts` у Twenty.
 */
const TOUCH_QUERY = "(hover: none) and (pointer: coarse)";

/**
 * Подписка на медиазапрос.
 *
 * `matchMedia` может отсутствовать: при серверном рендере нет `window`, а в
 * старых средах — самого API. Тогда подписка пустая, а значение приходит из
 * серверного снимка.
 */
function subscribe(query: string, onChange: () => void): () => void {
  if (typeof matchMedia !== "function") return () => undefined;

  const list = matchMedia(query);
  list.addEventListener("change", onChange);
  return () => list.removeEventListener("change", onChange);
}

function useMediaQuery(query: string): boolean {
  const subscribeToQuery = useCallback(
    (onChange: () => void) => subscribe(query, onChange),
    [query],
  );

  const getSnapshot = useCallback(
    () => (typeof matchMedia === "function" ? matchMedia(query).matches : false),
    [query],
  );

  // Серверный снимок — всегда `false`: на сервере ширина экрана неизвестна, и
  // любое другое значение было бы догадкой. Раскладка при этом не страдает,
  // потому что структура строится на CSS (см. комментарий выше).
  return useSyncExternalStore(subscribeToQuery, getSnapshot, () => false);
}

/**
 * Узкий экран: места под раскладку мало.
 *
 * Только для поведения, не для структуры. Пересчитывается при повороте
 * устройства и изменении размера окна.
 */
export function useIsMobile(): boolean {
  return useMediaQuery(MOBILE_QUERY);
}

/** Ввод касанием: hover недоступен, наведение и long-press ведут себя иначе. */
export function useIsTouchDevice(): boolean {
  return useMediaQuery(TOUCH_QUERY);
}
